def cols(rows):
    out = []
    for x in range(5):
        v = 0
        for y in range(7):
            if rows[y][x] == "#":
                v |= 1 << y
        out.append(v)
    return out


lines = ["// Generated by tools/make_font.py - do not edit by hand.",
         "#pragma once", "#include <stdint.h>",
         "// 5x7 glyphs for ASCII 32..127, 5 column bytes each, bit0 = top row.",
         "static const uint8_t FONT5X7[96][5] = {"]
for code in range(32, 128):
    ch = chr(code)
    key = ch.upper() if ch.isalpha() else ch
    rows = G.get(key, G["\x7f"])
    c = cols(rows)
    label = ch if 32 < code < 127 and ch not in "\\" else f"0x{code:02x}"
    lines.append("  {" + ", ".join(f"0x{v:02x}" for v in c) + "},  // " + label)
lines.append("};")

out = pathlib.Path(__file__).resolve().parent.parent / "src" / "font5x7.h"
out.write_text("\n".join(lines) + "\n")
missing = [chr(c) for c in range(33, 127) if (chr(c).upper() if chr(c).isalpha() else chr(c)) not in G]
print("wrote", out, "missing:", missing)
